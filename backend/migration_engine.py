def clean_text(val):
    if val is None:
        return ""
    s = str(val).strip()
    if s.lower() == "none" or s.lower() == "null":
        return ""
    return "".join(c for c in s if ord(c) >= 32 or c in "\n\r\t").strip()


def parse_float(val, default=0.0):
    try:
        if val is None:
            return default
        s = str(val).replace(",", "").replace("%", "").strip()
        return float(s) if s else default
    except Exception:
        return default


def parse_int(val, default=0):
    try:
        if val is None:
            return default
        s = str(val).replace(",", "").strip()
        return int(float(s)) if s else default
    except Exception:
        return default


def parse_date(date_str):
    if not date_str:
        return date.today().strftime("%Y-%m-%d")
    s = str(date_str).strip()
    for fmt in [
        "%m/%d/%y %H:%M:%S",
        "%m/%d/%Y %H:%M:%S",
        "%Y-%m-%d %H:%M:%S",
        "%Y-%m-%d",
        "%d/%m/%Y",
        "%m/%d/%y",
        "%d-%m-%Y"
    ]:
        try:
            return datetime.strptime(s, fmt).strftime("%Y-%m-%d")
        except Exception:
            pass
    if " " in s:
        s = s.split(" ")[0]
    return s


def map_voucher_type(raw_type):
    if not raw_type:
        return "Journal"
    t = str(raw_type).strip().upper()
    if t in ["SL", "SALES", "SALE", "SALEVOUCHER"]:
        return "Sales"
    elif t in ["PU", "PURCHASE", "PURC", "PURCHASEVOUCHER", "PR"]:
        return "Purchase"
    elif t in ["PY", "PAYMENT", "PYMT", "P", "CHPT", "CHQPYMT"]:
        return "Payment"
    elif t in ["RC", "RECEIPT", "RCPT", "R", "CHRT", "CHQRCPT"]:
        return "Receipt"
    elif t in ["CN", "CONTRA", "CNTR", "C"]:
        return "Contra"
    elif t in ["JV", "JOURNAL", "JRNL", "J"]:
        return "Journal"
    return "Journal"


def classify_stock_item(name):
    n = name.lower()
    if re.search(r'\bpaddy\b', n):
        if re.search(r'\bhusk\b', n):
            return "By-Product"
        return "Raw Paddy"
    elif re.search(r'\b(bran|husk|broken|nakku)\b', n):
        return "By-Product"
    elif re.search(r'\brice\b', n):
        return "Finished Rice"
    elif re.search(r'\b(bardana|bag|bags|thread|packing)\b', n):
        return "Packing Material"
    elif re.search(r'\b(machinery|dryer|parts|motor)\b', n):
        return "General Goods"
    return "General Goods"


